#!/usr/bin/env python3
"""Generate the LVGL fonts used by the Home Assistant dashboard screen.

LVGL's built-in Montserrat fonts only cover ASCII, so Home Assistant names
with characters such as å, ä, ö, é or ° would render as boxes. This script
rasterizes Montserrat (text) and Font Awesome 5 (icons), both shipped inside
the managed LVGL component, into LVGL 9 `lv_font_fmt_txt` C sources.

It only needs Pillow (with FreeType), so no npm `lv_font_conv` is required.

    python3 scripts/gen_dash_fonts.py

Re-run after `idf.py reconfigure` has populated managed_components/.
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "managed_components" / "lvgl__lvgl" / "scripts" / "generators" / "built_in_font"
OUT_DIR = ROOT / "main" / "assets"

TEXT_RANGES = [
    (0x20, 0x7E),      # ASCII
    (0xA0, 0x17F),     # Latin-1 supplement + Latin Extended-A (åäöéü°µ³ ...)
    (0x2013, 0x2014),  # en/em dash
    (0x2019, 0x2019),
    (0x201C, 0x201D),
    (0x2022, 0x2022),  # bullet
    (0x2026, 0x2026),  # ellipsis
    (0x20AC, 0x20AC),  # euro
    (0x2212, 0x2212),  # minus
]

# Font Awesome 5 code points used by ha_dash_icons.c. Keep the two in sync.
ICON_CODEPOINTS = [
    0xF0EB, 0xF011, 0xF1E6, 0xF205, 0xF2C9, 0xF043, 0xF023, 0xF3C1,
    0xF52B, 0xF52A, 0xF04B, 0xF0E7, 0xF185, 0xF186, 0xF015, 0xF26C, 0xF001,
    0xF2DC, 0xF06D, 0xF72E, 0xF007, 0xF0F3, 0xF0C2, 0xF06C, 0xF1B9, 0xF03D,
    0xF4B8, 0xF2D0, 0xF338, 0xF005, 0xF0D0, 0xF121, 0xF201, 0xF06E, 0xF554,
    0xF241, 0xF3FD, 0xF1EB, 0xF111, 0xF2E7, 0xF236, 0xF2CD, 0xF1BB, 0xF544,
    0xF75F, 0xF4D8, 0xF0F4, 0xF028, 0xF1CE, 0xF071, 0xF021, 0xF013, 0xF140,
    0xF0AC,
]

FONTS = [
    # (C symbol, source file, pixel size, code points)
    ("ui_font_dash16", "Montserrat-Medium.ttf", 16, None),
    ("ui_font_dash20", "Montserrat-Medium.ttf", 20, None),
    ("ui_font_dash32", "Montserrat-Medium.ttf", 32, None),
    ("ui_font_dash_icons", "FontAwesome5-Solid+Brands+Regular.woff", 30, ICON_CODEPOINTS),
]


def text_codepoints() -> list[int]:
    cps: list[int] = []
    for start, end in TEXT_RANGES:
        cps.extend(range(start, end + 1))
    return cps


def render_glyph(font: ImageFont.FreeTypeFont, cp: int):
    ch = chr(cp)
    adv = font.getlength(ch)
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, b""
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    # 4 bpp, rows packed continuously (no per-row byte alignment), high nibble first.
    nibbles = [(px * 15 + 127) // 255 for px in img.getdata()]
    if len(nibbles) % 2:
        nibbles.append(0)
    data = bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
    # ofs_y is the distance from the baseline to the bitmap's bottom edge, positive up.
    return adv, w, h, left, -bottom, data


def glyph_label(cp: int) -> str:
    if 0x20 <= cp < 0x7F and chr(cp) not in "\\\"*/":
        return f'U+{cp:04X} "{chr(cp)}"'
    return f"U+{cp:04X}"


def generate(symbol: str, source: str, size: int, cps: list[int] | None) -> Path:
    font = ImageFont.truetype(str(FONT_DIR / source), size)
    codepoints = sorted(cps if cps is not None else text_codepoints())

    bitmap = bytearray()
    glyphs = []
    present = []
    for cp in codepoints:
        if cp != 0x20 and cp != 0xA0 and font.getmask(chr(cp)).getbbox() is None:
            continue  # not in the font
        adv, w, h, ox, oy, data = render_glyph(font, cp)
        glyphs.append((cp, len(bitmap), round(adv * 16), w, h, ox, oy, data))
        present.append(cp)
        bitmap.extend(data)

    tops = [g[6] + g[4] for g in glyphs if g[4]]
    bottoms = [g[6] for g in glyphs if g[4]]
    ascent, descent = max(tops), -min(bottoms)
    line_height = ascent + descent

    for cp, _, adv16, w, h, ox, oy, _ in glyphs:
        if adv16 >= 4096 or w > 255 or h > 255 or not -128 <= ox <= 127 or not -128 <= oy <= 127:
            sys.exit(f"{symbol}: glyph U+{cp:04X} does not fit the compact glyph descriptor")

    range_start = present[0]
    if present[-1] - range_start >= 0xFFFF:
        sys.exit(f"{symbol}: code point span too large for one sparse cmap")

    out = []
    out.append("/*" + "*" * 78)
    out.append(f" * Size: {size} px")
    out.append(" * Bpp: 4")
    out.append(f" * Source: {source} (generated by scripts/gen_dash_fonts.py, do not edit)")
    out.append(" " + "*" * 78 + "/")
    out.append("")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for cp, _, _, w, h, _, _, data in glyphs:
        if not data:
            continue
        out.append(f"    /* {glyph_label(cp)} */")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    if not bitmap:
        out.append("    0x00,")
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for cp, idx, adv16, w, h, ox, oy, _ in glyphs:
        out.append(
            f"    {{.bitmap_index = {idx}, .adv_w = {adv16}, .box_w = {w}, .box_h = {h}, "
            f".ofs_x = {ox}, .ofs_y = {oy}}}, /* {glyph_label(cp)} */"
        )
    out.append("};")
    out.append("")
    out.append("static const uint16_t unicode_list[] = {")
    offsets = [cp - range_start for cp in present]
    for i in range(0, len(offsets), 12):
        out.append("    " + ", ".join(f"0x{o:x}" for o in offsets[i:i + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    out.append(
        f"    {{.range_start = {range_start}, .range_length = {present[-1] - range_start + 1}, "
        f".glyph_id_start = 1, .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, "
        f".list_length = {len(present)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},"
    )
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap,")
    out.append("    .glyph_dsc = glyph_dsc,")
    out.append("    .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL,")
    out.append("    .kern_scale = 0,")
    out.append("    .cmap_num = 1,")
    out.append("    .bpp = 4,")
    out.append("    .kern_classes = 0,")
    out.append("    .bitmap_format = 0,")
    out.append("};")
    out.append("")
    out.append(f"const lv_font_t {symbol} = {{")
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append(f"    .line_height = {line_height},")
    out.append(f"    .base_line = {descent},")
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append("    .underline_position = -2,")
    out.append("    .underline_thickness = 1,")
    out.append("#if LV_VERSION_CHECK(9, 3, 0)")
    out.append("    .static_bitmap = 1,")
    out.append("#endif")
    out.append("    .dsc = &font_dsc,")
    out.append("    .fallback = NULL,")
    out.append("    .user_data = NULL,")
    out.append("};")
    out.append("")

    path = OUT_DIR / f"{symbol}.c"
    path.write_text("\n".join(out), encoding="utf-8")
    missing = len(codepoints) - len(present)
    print(f"{path.relative_to(ROOT)}: {len(present)} glyphs, {len(bitmap)} bitmap bytes"
          + (f", {missing} code points not in font" if missing else ""))
    return path


def main() -> int:
    if not FONT_DIR.is_dir():
        sys.exit(f"missing {FONT_DIR}; run a build once so managed_components/ is populated")
    for symbol, source, size, cps in FONTS:
        generate(symbol, source, size, cps)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
